class LLMClient:
    """
    统一的 LLM 客户端
    支持 MiniMax，提供对话、补全等接口
    """

    def __init__(
        self,
        api_key: str = None,
        model: str = None,
        temperature: float = 0.6,
        max_tokens: int = 800,
    ):
        self.api_key = api_key or get_api_key()
        # 端点与模型：环境变量优先，否则按密钥来源推断（DeepSeek / MiniMax）
        _base_url, _model = get_llm_endpoint()
        self.base_url = _base_url
        self.model = model or _model
        self.temperature = temperature
        self.max_tokens = max_tokens
        self._llm: Optional[DeepSeekChat] = None

    @property
    def llm(self) -> DeepSeekChat:
        if self._llm is None:
            if not self.api_key:
                raise ValueError("API Key 未设置")
            self._llm = DeepSeekChat(
                api_key=self.api_key,
                model=self.model,
                temperature=self.temperature,
                max_tokens=self.max_tokens,
                base_url=self.base_url,
            )
        return self._llm

    def chat(
        self,
        messages: List[Dict[str, str]],
        temperature: float = None,
        max_tokens: int = None,
    ) -> str:
        """
        对话接口

        Args:
            messages: [{"role": "user/assistant/system", "content": "..."}]
            temperature: 温度参数
            max_tokens: 最大token数

        Returns:
            模型回复文本
        """
        if not self.api_key:
            return self._fallback_response()

        # 转换为 LangChain 消息格式
        langchain_messages = []
        for msg in messages:
            role = msg.get("role", "user")
            content = msg.get("content", "")

            if role == "system":
                langchain_messages.append(SystemMessage(content=content))
            elif role == "assistant":
                langchain_messages.append(AIMessage(content=content))
            else:
                langchain_messages.append(HumanMessage(content=content))

        # 调用模型
        llm_params = {}
        if temperature is not None:
            llm_params["temperature"] = temperature
        if max_tokens is not None:
            llm_params["max_tokens"] = max_tokens

        last_err = None
        for attempt in range(1, 4):
            try:
                response = self.llm.invoke(langchain_messages, **llm_params)
                return response.content if hasattr(response, "content") else str(response)
            except Exception as e:
                last_err = e
                print(f"[LLMClient] API调用失败(第{attempt}次): {e}")
                if attempt < 3:
                    time.sleep(2)

        print(f"[LLMClient] 重试3次仍失败: {last_err}")
        return self._fallback_response()

    def chat_with_langchain(
        self,
        messages: List[BaseMessage],
        temperature: float = None,
    ) -> str:
        """使用 LangChain 消息格式对话"""
        if not self.api_key:
            return self._fallback_response()

        try:
            llm_params = {}
            if temperature is not None:
                llm_params["temperature"] = temperature
            response = self.llm.invoke(messages, **llm_params)
            return response.content if hasattr(response, "content") else str(response)
        except Exception as e:
            print(f"[LLMClient] API调用失败: {e}")
            return self._fallback_response()

    def _fallback_response(self) -> str:
        """API 不可用时的默认回复"""
        return "[LLM暂时不可用，请检查API配置]"


